import "server-only";
import { prisma } from "@/lib/prisma";
import { addMonths, startOfMonth, endOfMonth, isAfter, isBefore, lastDayOfMonth } from "date-fns";
import type { ProjectionRange, VirtualOccurrence } from "../types";
import type { FinanceCashflowConfig } from "@prisma/client";

const IVA_CATEGORY_CODE = "EGR_IVA_F29";

type CategoryLite = { id: string; code: string; name: string };

export async function projectIvaFromDte(
  tenantId: string,
  range: ProjectionRange,
  codeToCategory: Map<string, CategoryLite>,
  config: FinanceCashflowConfig,
): Promise<VirtualOccurrence[]> {
  const cat = codeToCategory.get(IVA_CATEGORY_CODE);
  if (!cat) return [];

  const out: VirtualOccurrence[] = [];
  let periodCursor = startOfMonth(addMonths(range.from, -1));
  const lastPeriod = startOfMonth(range.to);

  while (!isAfter(periodCursor, lastPeriod)) {
    const periodStart = periodCursor;
    const periodEnd = endOfMonth(periodCursor);

    const [issued, received] = await Promise.all([
      prisma.financeDte.aggregate({
        where: {
          tenantId,
          direction: "ISSUED",
          dteType: { in: [33, 39] },
          date: { gte: periodStart, lte: periodEnd },
          siiStatus: { in: ["ACCEPTED", "SENT"] },
        },
        _sum: { taxAmount: true },
      }),
      prisma.financeDte.aggregate({
        where: {
          tenantId,
          direction: "RECEIVED",
          dteType: { in: [33] },
          date: { gte: periodStart, lte: periodEnd },
          receptionStatus: { in: ["ACCEPTED"] },
        },
        _sum: { taxAmount: true },
      }),
    ]);

    const debit = Number(issued._sum.taxAmount ?? 0);
    const credit = Number(received._sum.taxAmount ?? 0);
    const net = debit - credit;

    if (net > 0) {
      const payMonth = addMonths(periodCursor, 1);
      const last = lastDayOfMonth(payMonth);
      const scheduledDate = new Date(
        payMonth.getFullYear(),
        payMonth.getMonth(),
        Math.min(config.ivaPayDay, last.getDate()),
      );
      if (!isBefore(scheduledDate, range.from) && !isAfter(scheduledDate, range.to)) {
        out.push({
          id: null,
          itemId: null,
          source: "IVA",
          categoryId: cat.id,
          categoryCode: cat.code,
          categoryName: cat.name,
          kind: "EXPENSE",
          name: `IVA F29 ${periodCursor.toISOString().slice(0, 7)}`,
          description: `Débito: ${debit.toLocaleString("es-CL")} − Crédito: ${credit.toLocaleString("es-CL")}`,
          scheduledDate,
          effectiveDate: null,
          amountClp: net,
          amountOriginal: net,
          currency: "CLP",
          ufValueUsed: null,
          status: "PROJECTED",
          installationId: null,
          installationName: null,
          bankTransactionId: null,
          isVirtual: true,
          isAutoGenerated: true,
          actualAmountClp: null,
          varianceClp: null,        });
      }
    }

    periodCursor = addMonths(periodCursor, 1);
  }

  return out;
}
