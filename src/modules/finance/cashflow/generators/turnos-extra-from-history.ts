import "server-only";
import { prisma } from "@/lib/prisma";
import { subWeeks, addWeeks, startOfISOWeek, isAfter, isBefore } from "date-fns";
import type { ProjectionRange, VirtualOccurrence } from "../types";

const TE_CATEGORY_CODE = "EGR_TURNO_EXTRA";

type CategoryLite = { id: string; code: string; name: string };

export async function projectTurnosExtraFromHistory(
  tenantId: string,
  range: ProjectionRange,
  codeToCategory: Map<string, CategoryLite>,
): Promise<VirtualOccurrence[]> {
  const cat = codeToCategory.get(TE_CATEGORY_CODE);
  if (!cat) return [];

  const since = subWeeks(new Date(), 8);
  const tes = await prisma.opsTurnoExtra.findMany({
    where: { tenantId, date: { gte: since } },
    select: {
      installationId: true,
      amountClp: true,
      installation: { select: { name: true } },
    },
  });

  const byInstall = new Map<string, { name: string; total: number; count: number }>();
  for (const te of tes) {
    if (!te.installationId) continue;
    const cur = byInstall.get(te.installationId) ?? {
      name: te.installation?.name ?? "Sin nombre",
      total: 0,
      count: 0,
    };
    cur.total += Number(te.amountClp ?? 0);
    cur.count++;
    byInstall.set(te.installationId, cur);
  }

  const out: VirtualOccurrence[] = [];
  let cursor = startOfISOWeek(range.from);
  while (!isAfter(cursor, range.to)) {
    const friday = new Date(cursor);
    friday.setDate(friday.getDate() + 4);
    if (!isBefore(friday, range.from) && !isAfter(friday, range.to)) {
      for (const [installId, info] of byInstall) {
        const weeklyAvg = info.total / 8;
        if (weeklyAvg <= 0) continue;
        out.push({
          id: null,
          itemId: null,
          source: "TURNOS_EXTRA",
          categoryId: cat.id,
          categoryCode: cat.code,
          categoryName: cat.name,
          kind: "EXPENSE",
          name: `Turnos extra · ${info.name}`,
          description: `Promedio rolling 8 semanas (${info.count} TE históricos)`,
          scheduledDate: friday,
          effectiveDate: null,
          amountClp: weeklyAvg,
          amountOriginal: weeklyAvg,
          currency: "CLP",
          ufValueUsed: null,
          status: "PROJECTED",
          installationId: installId,
          installationName: info.name,
          crmAccountId: null,
          bankTransactionId: null,
          isVirtual: true,
          isAutoGenerated: true,
          actualAmountClp: null,
          varianceClp: null,
          hasIpcAdjustment: false,
          ipcAdjustmentMonths: null,
          dteId: null,
          nickname: null,
          modoCobro: "DIRECTO",
        });
      }
    }
    cursor = addWeeks(cursor, 1);
  }

  return out;
}
