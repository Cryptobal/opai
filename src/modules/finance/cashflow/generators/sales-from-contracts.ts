import "server-only";
import { prisma } from "@/lib/prisma";
import { addMonths, isAfter, isBefore } from "date-fns";
import type { ProjectionRange, VirtualOccurrence } from "../types";
import { resolveUfForOccurrence } from "../uf-resolver";
import {
  firstBusinessDayOfMonth,
  lastBusinessDayOfMonth,
  firstMondayOfMonth,
} from "@/lib/business-days";

const ACTIVE_QUOTE_STATUSES = ["accepted", "active", "in_progress", "approved"];
const SALES_CATEGORY_CODE = "ING_VENTA_CONTRATO";

type CategoryLite = { id: string; code: string; name: string };

export async function projectSalesFromContracts(
  tenantId: string,
  range: ProjectionRange,
  codeToCategory: Map<string, CategoryLite>,
): Promise<VirtualOccurrence[]> {
  const cat = codeToCategory.get(SALES_CATEGORY_CODE);
  if (!cat) return [];

  const quotes = await prisma.cpqQuote.findMany({
    where: {
      tenantId,
      status: { in: ACTIVE_QUOTE_STATUSES },
      contractStartDate: { not: null },
    },
    select: {
      id: true,
      name: true,
      clientName: true,
      accountId: true,
      installationId: true,
      monthlyCost: true,
      currency: true,
      contractStartDate: true,
      contractDuration: true,
      paymentDays: true,
      paymentDayMode: true,
      paymentTerms: true,
      realAnnualIncrement: true,
      installation: { select: { id: true, name: true } },
    },
  });

  const out: VirtualOccurrence[] = [];

  for (const q of quotes) {
    if (!q.contractStartDate) continue;
    const monthlyAmount = Number(q.monthlyCost ?? 0);
    if (monthlyAmount <= 0) continue;

    const contractEnd = addMonths(q.contractStartDate, q.contractDuration ?? 12);
    let monthCursor = new Date(q.contractStartDate);
    let monthIndex = 0;

    while (!isAfter(monthCursor, range.to) && !isAfter(monthCursor, contractEnd)) {
      const payDay = q.paymentDays ?? 5;
      const isPostpago =
        (q.paymentTerms ?? "").toLowerCase().includes("contrafactura") ||
        (q.paymentTerms ?? "").toLowerCase().includes("post");
      const billingMonth = isPostpago ? addMonths(monthCursor, 1) : monthCursor;

      const mode = q.paymentDayMode ?? "SPECIFIC_DAY";
      const y = billingMonth.getFullYear();
      const mo = billingMonth.getMonth() + 1; // 1-12 para los helpers
      let scheduledDate: Date;
      switch (mode) {
        case "FIRST_BUSINESS_DAY":
          scheduledDate = firstBusinessDayOfMonth(y, mo);
          break;
        case "LAST_BUSINESS_DAY":
          scheduledDate = lastBusinessDayOfMonth(y, mo);
          break;
        case "FIRST_MONDAY":
          scheduledDate = firstMondayOfMonth(y, mo);
          break;
        case "SPECIFIC_DAY":
        default:
          scheduledDate = new Date(y, mo - 1, Math.min(payDay, 28));
          break;
      }

      if (isBefore(scheduledDate, range.from) || isAfter(scheduledDate, range.to)) {
        monthCursor = addMonths(monthCursor, 1);
        monthIndex++;
        continue;
      }

      const yearsElapsed = Math.floor(monthIndex / 12);
      const incrementPct = (q.realAnnualIncrement ?? 0) / 100;
      const amount = monthlyAmount * Math.pow(1 + incrementPct, yearsElapsed);

      let amountClp: number;
      let ufValueUsed: number | null = null;
      if (q.currency === "UF") {
        ufValueUsed = await resolveUfForOccurrence("RUN_DAY", null, scheduledDate);
        amountClp = amount * ufValueUsed;
      } else {
        amountClp = amount;
      }

      out.push({
        id: null,
        itemId: null,
        source: "CONTRACT",
        categoryId: cat.id,
        categoryCode: cat.code,
        categoryName: cat.name,
        kind: "INCOME",
        name: q.installation?.name ?? q.clientName ?? q.name ?? "Contrato",
        description: `Cotización ${q.id.slice(0, 8)} · ${q.currency} ${amount.toFixed(2)}/mes`,
        scheduledDate,
        effectiveDate: null,
        amountClp,
        amountOriginal: amount,
        currency: q.currency,
        ufValueUsed,
        status: "PROJECTED",
        installationId: q.installationId,
        installationName: q.installation?.name ?? null,
        crmAccountId: q.accountId ?? null,
        bankTransactionId: null,
        isVirtual: true,
        isAutoGenerated: true,
        actualAmountClp: null,
        varianceClp: null,
        hasIpcAdjustment: false,
        ipcAdjustmentMonths: null,
        dteId: null,
      });

      monthCursor = addMonths(monthCursor, 1);
      monthIndex++;
    }
  }

  return out;
}
