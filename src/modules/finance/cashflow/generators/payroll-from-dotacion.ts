import "server-only";
import { prisma } from "@/lib/prisma";
import { addMonths, lastDayOfMonth, startOfMonth, isAfter, isBefore } from "date-fns";
import type { ProjectionRange, VirtualOccurrence } from "../types";
import type { FinanceCashflowConfig } from "@prisma/client";
import { computeEmployerCost } from "@/modules/payroll/engine/compute-employer-cost";

const PAYROLL_CATEGORY_CODE = "EGR_SUELDO";

type CategoryLite = { id: string; code: string; name: string };

export async function projectPayrollFromDotacion(
  tenantId: string,
  range: ProjectionRange,
  codeToCategory: Map<string, CategoryLite>,
  config: FinanceCashflowConfig,
): Promise<VirtualOccurrence[]> {
  const cat = codeToCategory.get(PAYROLL_CATEGORY_CODE);
  if (!cat) return [];

  const puestos = await prisma.opsPuestoOperativo.findMany({
    where: { tenantId, active: true, salaryStructureId: { not: null } },
    select: {
      id: true,
      installationId: true,
      installation: { select: { id: true, name: true } },
      salaryStructure: { select: { baseSalary: true } },
    },
  });

  const useFullCompute = puestos.length <= 50;

  const byInstall = new Map<string, { name: string; monthlyEmployerCost: number }>();
  for (const p of puestos) {
    if (!p.installationId || !p.salaryStructure) continue;
    const baseSalary = Number(p.salaryStructure.baseSalary ?? 0);
    if (baseSalary <= 0) continue;

    let employerCost = baseSalary * 1.45;
    if (useFullCompute) {
      try {
        const r = await computeEmployerCost({
          base_salary_clp: baseSalary,
          contract_type: "indefinite",
        });
        if (r?.monthly_employer_cost_clp) {
          employerCost = r.monthly_employer_cost_clp;
        }
      } catch {
        // fallback al factor
      }
    }

    const cur = byInstall.get(p.installationId) ?? {
      name: p.installation?.name ?? "Sin instalación",
      monthlyEmployerCost: 0,
    };
    cur.monthlyEmployerCost += employerCost;
    byInstall.set(p.installationId, cur);
  }

  const out: VirtualOccurrence[] = [];

  let cursor = startOfMonth(range.from);
  while (!isAfter(cursor, range.to)) {
    const payMonth = addMonths(cursor, 1);
    const payDay = config.payrollPayDay;
    let scheduledDate: Date;
    if (payDay === -1) {
      scheduledDate = lastDayOfMonth(payMonth);
    } else {
      const last = lastDayOfMonth(payMonth);
      scheduledDate = new Date(payMonth.getFullYear(), payMonth.getMonth(), Math.min(payDay, last.getDate()));
    }
    if (!isBefore(scheduledDate, range.from) && !isAfter(scheduledDate, range.to)) {
      for (const [installId, info] of byInstall) {
        if (info.monthlyEmployerCost <= 0) continue;
        out.push({
          id: null,
          itemId: null,
          source: "PAYROLL",
          categoryId: cat.id,
          categoryCode: cat.code,
          categoryName: cat.name,
          kind: "EXPENSE",
          name: `Sueldos · ${info.name}`,
          description: `Costo empleador estimado período ${cursor.toISOString().slice(0, 7)}`,
          scheduledDate,
          effectiveDate: null,
          amountClp: info.monthlyEmployerCost,
          amountOriginal: info.monthlyEmployerCost,
          currency: "CLP",
          ufValueUsed: null,
          status: "PROJECTED",
          installationId: installId,
          installationName: info.name,
          crmAccountId: null,
          bankTransactionId: null,
          isVirtual: true,
          isAutoGenerated: true,
          actualAmountClp: null,
          varianceClp: null,
          hasIpcAdjustment: false,
          ipcAdjustmentMonths: null,
        });
      }
    }
    cursor = addMonths(cursor, 1);
  }

  return out;
}
