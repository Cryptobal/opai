import "server-only";
import { prisma } from "@/lib/prisma";
import { addMonths, addWeeks, isAfter } from "date-fns";
import type { ProjectionRange, VirtualOccurrence } from "../types";
import { resolveUfForOccurrence } from "../uf-resolver";

const SALES_CATEGORY_CODE = "ING_VENTA_CONTRATO";

type CategoryLite = { id: string; code: string; name: string };

interface RecurringLine {
  quantity?: number | string;
  unitPrice?: number | string;
  unitPriceUf?: number | string;
  discountPct?: number | string;
}

export async function projectRecurringDtes(
  tenantId: string,
  range: ProjectionRange,
  codeToCategory: Map<string, CategoryLite>,
): Promise<VirtualOccurrence[]> {
  const cat = codeToCategory.get(SALES_CATEGORY_CODE);
  if (!cat) return [];

  const templates = await prisma.financeDteRecurringTemplate.findMany({
    where: { tenantId, isActive: true },
    select: {
      id: true,
      name: true,
      receiverName: true,
      currency: true,
      lines: true,
      frequency: true,
      dayOfMonth: true,
      dayOfWeek: true,
      monthOfYear: true,
      startDate: true,
      endDate: true,
      ufFixingPolicy: true,
      ufFixingDay: true,
      installationId: true,
    },
  });

  const out: VirtualOccurrence[] = [];
  for (const t of templates) {
    const lines = (t.lines as RecurringLine[] | null) ?? [];
    const subtotal = lines.reduce((s, l) => {
      const qty = Number(l.quantity ?? 1);
      const price = Number(l.unitPrice ?? l.unitPriceUf ?? 0);
      const disc = Number(l.discountPct ?? 0) / 100;
      return s + qty * price * (1 - disc);
    }, 0);
    if (subtotal <= 0) continue;

    let cursor = new Date(t.startDate);
    const stop = t.endDate ? new Date(t.endDate) : range.to;
    while (!isAfter(cursor, range.to) && !isAfter(cursor, stop)) {
      if (cursor >= range.from && cursor <= range.to) {
        let amountClp = subtotal;
        let ufVal: number | null = null;
        if (t.currency === "UF") {
          ufVal = await resolveUfForOccurrence(t.ufFixingPolicy, t.ufFixingDay, cursor);
          amountClp = subtotal * ufVal * 1.19;
        } else {
          amountClp = subtotal * 1.19;
        }
        out.push({
          id: null,
          itemId: null,
          source: "RECURRING_DTE",
          categoryId: cat.id,
          categoryCode: cat.code,
          categoryName: cat.name,
          kind: "INCOME",
          name: `DTE recurrente · ${t.name}`,
          description: `${t.receiverName} · ${t.currency}`,
          notes: null,
          scheduledDate: new Date(cursor),
          effectiveDate: null,
          amountClp,
          amountOriginal: subtotal,
          currency: t.currency,
          ufValueUsed: ufVal,
          status: "PROJECTED",
          installationId: t.installationId,
          installationName: null,
          crmAccountId: null,
          bankTransactionId: null,
          isVirtual: true,
          isAutoGenerated: true,
          actualAmountClp: null,
          varianceClp: null,
          hasIpcAdjustment: false,
          ipcAdjustmentMonths: null,
          dteId: null,
          nickname: null,
          modoCobro: "DIRECTO",
        });
      }
      switch (t.frequency) {
        case "monthly":
          cursor = addMonths(cursor, 1);
          break;
        case "biweekly":
          cursor = addWeeks(cursor, 2);
          break;
        case "weekly":
          cursor = addWeeks(cursor, 1);
          break;
        case "yearly":
          cursor = addMonths(cursor, 12);
          break;
        default:
          cursor = addMonths(cursor, 1);
      }
    }
  }

  return out;
}
