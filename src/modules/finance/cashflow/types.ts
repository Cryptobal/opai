export interface VirtualOccurrence {
  id: string | null;
  itemId: string | null;
  source: FinanceCashflowItemSource;
  categoryId: string | null;
  categoryCode: string;
  categoryName: string;
  kind: FinanceCashflowItemKind;
  name: string;
  description: string | null;
  /** Nota libre del usuario sobre esta cuota (contexto, recordatorios,
   *  detalles que no caben en otros campos). Editable desde el detail sheet.
   *  null = sin nota. */
  notes: string | null;
  scheduledDate: Date;
  effectiveDate: Date | null;
  amountClp: number;
  amountOriginal: number;
  currency: string;
  ufValueUsed: number | null;
  status: FinanceCashflowOccurrenceStatus;
  installationId: string | null;
  installationName: string | null;
  /** Cuenta CRM dueña del ítem (para links a contratos / cotización origen). */
  crmAccountId: string | null;
  /** Nombre de la cuenta CRM (cliente) dueña del ítem. Resuelto en el motor de
   *  proyección a partir de crmAccountId. Permite a la UI mostrar
   *  "Cuenta – Instalación" y ordenar por cliente. null si no tiene cuenta o no
   *  se pudo resolver; undefined en occurrences que aún no pasaron por el
   *  enriquecido (no debería ocurrir en las que llegan a la UI). */
  crmAccountName?: string | null;
  bankTransactionId: string | null;
  isVirtual: boolean;
  isAutoGenerated: boolean;
  /** Monto realmente ejecutado en banco (cuando hay match con un bank tx). null = aún no conciliado. */
  actualAmountClp: number | null;
  /** Diferencia real − proyectado. Positivo = gasté más / cobré más de lo proyectado. null si no hay actual. */
  varianceClp: number | null;
  /**
   * El item de origen tiene reajuste de IPC configurado. Permite a la UI
   * marcar el contrato con un badge permanente, independiente de si hay
   * un ajuste PENDING en los próximos 30 días.
   */
  hasIpcAdjustment: boolean;
  /** Frecuencia del reajuste IPC en meses (6, 12, etc). */
  ipcAdjustmentMonths: number | null;
  /** DTE vinculado a la occurrence materializada (null si proyectada o sin vínculo). */
  dteId: string | null;
  /** El monto de esta occurrence fue fijado manualmente por el usuario
   *  (`amountOverride != null`) — vía "Editar monto" / "Igualar a factura".
   *  La UI lo marca como override manual y ofrece revertir al calculado. */
  hasAmountOverride?: boolean;
  /** Alias visible del contrato. Permite distinguir varios contratos del
   *  mismo cliente con la misma instalación (ej. "Ciclo proforma" vs
   *  "Facturación directa" en Transmat). null = usar nombre técnico. */
  nickname: string | null;
  /** Patrón de cobro del contrato. DIRECTO = cliente paga a la cuenta del
   *  tenant (default). FACTORING = factura cedida al factor (cobro
   *  acelerado, descontado al emitir cada factura). Default DIRECTO para
   *  occurrences sintéticas / huérfanas que no tienen item asociado. */
  modoCobro: "DIRECTO" | "FACTORING";
  /** Etapa del ciclo resuelta a nivel de CELDA (item+bucket) desde el DTE
   *  vinculado: PROJECTED(Programada)/DRAFT(Borrador)/INVOICED(Facturada)/
   *  CEDED(Factorizada)/PAID(Pagada). El motor la stampa en TODAS las
   *  occurrences de la celda (incl. la proyección del contrato) para que la fila
   *  del flujo muestre la etapa real aunque el DTE viva en una occurrence
   *  hermana (sombra). undefined = aún sin DTE en la celda → Programada. */
  cellStatus?: CashflowCellStatus;
  /** Folio del DTE de la celda (si está facturada). null/undefined = sin folio. */
  dteFolio?: number | null;
  /** Días de mora de la celda (si está vencida). */
  daysOverdue?: number;
  /** true cuando el DTE está cedido a factoring Y el depósito del cesionario
   *  ya se concilió (FactoringOperation en FUNDED/COLLECTED). Permite mostrar
   *  "Factorizada · cobrada" en vez de "Factorizada" plana: la plata ya entró
   *  al banco aunque el DTE siga en CEDED (su cobro lo gestiona el factoring). */
  factoringCollected?: boolean;
  /** Movimiento originado en conciliación bancaria SIN item de contrato/nómina
   *  detrás: bank-link huérfano (`Conciliación · <cat>`) o item MANUAL creado
   *  por `assignBankTxToCategory` rama B (nombre = glosa del banco, ej.
   *  "Compra OPENAI* CHATGPT C"). La grilla de EGRESOS los colapsa dentro de su
   *  cuenta en vez de darles fila propia. No aplica a INGRESOS. */
  isConciliacion?: boolean;
  /** 2ª+ factura del mismo item de contrato en el mismo bucket. Obtiene
   *  sub-fila propia en buildRows (badge "+ EXTRA") en vez de colapsar en la
   *  celda del contrato, donde sólo era visible en el popover. */
  isExtraInvoice?: boolean;
}

export interface ProjectionRange {
  from: Date;
  to: Date;
  granularity: "weekly" | "monthly";
}

export interface ProjectionBucket {
  key: string;
  label: string;
  start: Date;
  end: Date;
  income: number;
  expense: number;
  net: number;
  /** Suma de actualAmountClp para occurrences PAID dentro del bucket (solo INCOME). */
  actualIncome: number;
  /** Suma de actualAmountClp para occurrences PAID dentro del bucket (solo EXPENSE). */
  actualExpense: number;
  /** real − proyectado para todo el bucket: (actualIncome − income) − (actualExpense − expense). */
  varianceClp: number;
  /** Suma de créditos (amount > 0) de FinanceBankTransaction visibles en el bucket. */
  actualBankIncome: number;
  /** Suma de débitos (amount < 0) en valor absoluto. */
  actualBankExpense: number;
  /** Net real de cartola = actualBankIncome − actualBankExpense. */
  actualBankNet: number;
  /** Diferencia entre lo que el banco ejecutó y lo proyectado:
   *  (actualBankIncome − income) − (actualBankExpense − expense). */
  bankVarianceClp: number;
  occurrences: VirtualOccurrence[];
}

/**
 * Estado de una celda de proyección respecto a su DTE vinculado:
 *  - PROJECTED: sin DTE vinculado (cuota proyectada del contrato).
 *  - DRAFT:     DTE en borrador (sin folio asignado) o pendiente envío SII.
 *  - INVOICED:  DTE aceptado SII, sin factoring activo, no pagado todavía.
 *  - CEDED:     DTE cedido a factoring (paymentStatus=CEDED o FactoringOperation activa).
 *  - PAID:      DTE pagado.
 */
export type CashflowCellStatus =
  | "PROJECTED"
  | "DRAFT"
  | "INVOICED"
  | "CEDED"
  | "PAID"
  | "VOIDED";

export interface ProjectionRowItemValue {
  bucketKey: string;
  amount: number;
  /** Suma de actualAmountClp en este bucket (null si no hay conciliación). */
  actualAmount: number | null;
  /** id de una occurrence representativa (no PAID, materializada) para DnD/popover. */
  occurrenceId: string | null;
  /** scheduledDate (yyyy-MM-dd) de una cuota representativa del bucket. Permite
   *  materializar al primer move/amount aunque occurrenceId sea null. */
  scheduledDate: string;
  /** Estado de la celda respecto al DTE vinculado. PROJECTED si no hay vínculo. */
  cellStatus?: CashflowCellStatus;
  /** dteId vinculado, si existe — para deep-link al DTE. */
  dteId?: string | null;
  /** Alguna occurrence de la celda tiene monto fijado manualmente
   *  (`amountOverride`). La UI muestra un badge "editado" y ofrece revertir. */
  hasAmountOverride?: boolean;
  /** Alguna occurrence de la celda está conciliada con el banco
   *  (`bankTransactionId != null`) — la celda quedó FIJA (no editable),
   *  tenga o no un DTE cobrado detrás. La UI la marca con candado. Sin esto,
   *  un gasto conciliado sin factura (ej. OpenAI, Contador) quedaba fijo pero
   *  sin candado, y la leyenda "candado = conciliado (fijo)" mentía. */
  reconciled?: boolean;
  /** Folio del DTE vinculado, si existe. Usado en el tooltip de la celda
   *  para mostrar "Factura N° {folio}" al hacer hover. */
  dteFolio?: number | null;
  /** Monto bruto (totalAmount) del DTE vinculado en CLP. Sirve como
   *  fuente del botón "Igualar a factura" en el popover de la celda:
   *  el bruto es lo que debe quedar en la línea, y el costo de
   *  factoring (si lo hay) vive en su propia categoría sin duplicarse. */
  dteGrossAmount?: number | null;
  /** Días de mora si INVOICED + overdue (positivos), 0 si al día. */
  daysOverdue?: number;
  /** Resumen de TODOS los DTEs conciliados con esta celda. Cuando hay >1,
   *  el popover lista cada factura (folio, fecha emisión, monto, link) y
   *  el botón "Igualar" suma los totales en lugar de matchear contra una
   *  sola. Vacío o ausente = celda proyectada sin conciliar. */
  dtes?: CellDteSummary[];
  /** Monto del ajuste contable (write-off) imputado a esta celda. Presente
   *  cuando el DTE vinculado tuvo un FinanceJournalEntry con sourceType=
   *  RECONCILIATION. Positivo = diferencia en contra (pérdida); negativo =
   *  diferencia a favor (ganancia). Sirve para mostrar un badge "Δ" en la
   *  celda y un tooltip extendido con el detalle del ajuste. */
  writeOffAmount?: number | null;
}

