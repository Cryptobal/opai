export interface VirtualOccurrence {
  id: string | null;
  itemId: string | null;
  source: FinanceCashflowItemSource;
  categoryId: string | null;
  categoryCode: string;
  categoryName: string;
  kind: FinanceCashflowItemKind;
  name: string;
  description: string | null;
  scheduledDate: Date;
  effectiveDate: Date | null;
  amountClp: number;
  amountOriginal: number;
  currency: string;
  ufValueUsed: number | null;
  status: FinanceCashflowOccurrenceStatus;
  installationId: string | null;
  installationName: string | null;
  /** Cuenta CRM dueña del ítem (para links a contratos / cotización origen). */
  crmAccountId: string | null;
  bankTransactionId: string | null;
  isVirtual: boolean;
  isAutoGenerated: boolean;
  /** Monto realmente ejecutado en banco (cuando hay match con un bank tx). null = aún no conciliado. */
  actualAmountClp: number | null;
  /** Diferencia real − proyectado. Positivo = gasté más / cobré más de lo proyectado. null si no hay actual. */
  varianceClp: number | null;
  /**
   * El item de origen tiene reajuste de IPC configurado. Permite a la UI
   * marcar el contrato con un badge permanente, independiente de si hay
   * un ajuste PENDING en los próximos 30 días.
   */
  hasIpcAdjustment: boolean;
  /** Frecuencia del reajuste IPC en meses (6, 12, etc). */
  ipcAdjustmentMonths: number | null;
  /** DTE vinculado a la occurrence materializada (null si proyectada o sin vínculo). */
  dteId: string | null;
}

export interface ProjectionRange {
  from: Date;
  to: Date;
  granularity: "weekly" | "monthly";
}

export interface ProjectionBucket {
  key: string;
  label: string;
  start: Date;
  end: Date;
  income: number;
  expense: number;
  net: number;
  /** Suma de actualAmountClp para occurrences PAID dentro del bucket (solo INCOME). */
  actualIncome: number;
  /** Suma de actualAmountClp para occurrences PAID dentro del bucket (solo EXPENSE). */
  actualExpense: number;
  /** real − proyectado para todo el bucket: (actualIncome − income) − (actualExpense − expense). */
  varianceClp: number;
  /** Suma de créditos (amount > 0) de FinanceBankTransaction visibles en el bucket. */
  actualBankIncome: number;
  /** Suma de débitos (amount < 0) en valor absoluto. */
  actualBankExpense: number;
  /** Net real de cartola = actualBankIncome − actualBankExpense. */
  actualBankNet: number;
  /** Diferencia entre lo que el banco ejecutó y lo proyectado:
   *  (actualBankIncome − income) − (actualBankExpense − expense). */
  bankVarianceClp: number;
  occurrences: VirtualOccurrence[];
}

/**
 * Estado de una celda de proyección respecto a su DTE vinculado:
 *  - PROJECTED: sin DTE vinculado (cuota proyectada del contrato).
 *  - DRAFT:     DTE en borrador (sin folio asignado) o pendiente envío SII.
 *  - INVOICED:  DTE aceptado SII, sin factoring activo, no pagado todavía.
 *  - CEDED:     DTE cedido a factoring (paymentStatus=CEDED o FactoringOperation activa).
 *  - PAID:      DTE pagado.
 */
export type CashflowCellStatus =
  | "PROJECTED"
  | "DRAFT"
  | "INVOICED"
  | "CEDED"
  | "PAID";

export interface ProjectionRowItemValue {
  bucketKey: string;
  amount: number;
  /** Suma de actualAmountClp en este bucket (null si no hay conciliación). */
  actualAmount: number | null;
  /** id de una occurrence representativa (no PAID, materializada) para DnD/popover. */
  occurrenceId: string | null;
  /** scheduledDate (yyyy-MM-dd) de una cuota representativa del bucket. Permite
   *  materializar al primer move/amount aunque occurrenceId sea null. */
  scheduledDate: string;
  /** Estado de la celda respecto al DTE vinculado. PROJECTED si no hay vínculo. */
  cellStatus?: CashflowCellStatus;
  /** dteId vinculado, si existe — para deep-link al DTE. */
  dteId?: string | null;
  /** Folio del DTE vinculado, si existe. Usado en el tooltip de la celda
   *  para mostrar "Factura N° {folio}" al hacer hover. */
  dteFolio?: number | null;
  /** Monto bruto (totalAmount) del DTE vinculado en CLP. Sirve como
   *  fuente del botón "Igualar a factura" en el popover de la celda:
   *  el bruto es lo que debe quedar en la línea, y el costo de
   *  factoring (si lo hay) vive en su propia categoría sin duplicarse. */
  dteGrossAmount?: number | null;
  /** Días de mora si INVOICED + overdue (positivos), 0 si al día. */
  daysOverdue?: number;
  /** Resumen de TODOS los DTEs conciliados con esta celda. Cuando hay >1,
   *  el popover lista cada factura (folio, fecha emisión, monto, link) y
   *  el botón "Igualar" suma los totales en lugar de matchear contra una
   *  sola. Vacío o ausente = celda proyectada sin conciliar. */
  dtes?: CellDteSummary[];
}

/** Resumen mínimo de un DTE conciliado a una celda del cashflow. Permite
 *  listar facturas asociadas, mostrar fecha de emisión (útil para detectar
 *  "factura antigua cobrada hoy") y linkear a la factura origen. */
export interface CellDteSummary {
  id: string;
  folio: number | null;
  /** Monto bruto del DTE (totalAmount) en CLP. */
  totalAmount: number;
  /** Fecha de emisión yyyy-MM-dd. */
  issueDate: string;
  /** True si hay un FactoringOperation activo asociado al DTE. */
  hasFactoring: boolean;
  /** Estado derivado para este DTE (PAID/CEDED/INVOICED/DRAFT). */
  cellStatus: CashflowCellStatus;
  /** Días de mora (positivo = vencido, 0 = al día). */
  daysOverdue: number;
}

export interface ProjectionRowItemDetail {
  itemId: string;
  itemName: string;
  installationId: string | null;
  installationName: string | null;
  /** Cuenta CRM dueña del ítem — habilita link al tab Contratos. */
  crmAccountId: string | null;
  /** Nombre del cliente (CrmAccount.name) para mostrar agrupación en UI. */
  crmAccountName: string | null;
  /** Monto base del item en su moneda original (UF o CLP), tal como se
   *  guardó. Se muestra al lado del nombre para que el usuario vea el
   *  "precio del contrato" sin tener que calcularlo desde los buckets. */
  baseAmount: number;
  /** Moneda del item ("CLP" | "UF"). Útil para mostrar badge al lado del nombre. */
  currency: string;
  source: FinanceCashflowItemSource;
  /** Código del contrato CpqQuote o ref similar para mostrar en badge. */
  sourceRefCode: string | null;
  /** Reajuste IPC configurado en el item. Permite mostrar badge permanente
   *  en la UI (no solo cuando hay ajuste PENDING próximo). */
  hasIpcAdjustment: boolean;
  /** Frecuencia del reajuste IPC en meses (6, 12). null si no aplica. */
  ipcAdjustmentMonths: number | null;
  /** Headcount planificado de la instalación (SUM(requiredGuards) de
   *  OpsPuestoOperativo activos). 0 si el item no tiene instalación o si
   *  la instalación no tiene puestos. */
  headcount: number;
  values: ProjectionRowItemValue[];
  total: number;
  totalActual: number;
}

export interface ProjectionRow {
  categoryId: string | null;
  categoryCode: string;
  categoryName: string;
  kind: FinanceCashflowItemKind;
  values: { bucketKey: string; amount: number }[];
  total: number;
  /** Sub-filas por item (instalación / contrato / template / etc) para expansión. */
  items: ProjectionRowItemDetail[];
}

export interface CumulativeBalancePoint {
  bucketKey: string;
  /** Saldo proyectado al final del bucket: opening + Σ(net hasta bucket i). */
  projectedClp: number;
  /**
   * Saldo bancario real al final del bucket: opening + Σ(actualBankNet hasta i).
   * Null para buckets futuros (start > today).
   */
  realBankClp: number | null;
  /**
   * Drift acumulado = realBankClp − projectedClp.
   * Null para buckets futuros. Positivo = banco tiene más plata; negativo = menos.
   */
  cumulativeBankVarianceClp: number | null;
}

/** Link bancario conciliado que no se pudo atribuir a una categoría
 *  específica (o que cayó a "Otros" como fallback). La UI lo usa para
 *  alertar al usuario y guiarlo a configurar mappings de cuenta o
 *  regenerar líneas del DTE. */
export interface UnresolvedBankLinkInfo {
  bankTransactionId: string;
  transactionDate: Date;
  amountClp: number;
  targetType: string;
  targetRef: string | null;
  reason: string;
}

export interface ProjectionMatrix {
  range: ProjectionRange;
  buckets: ProjectionBucket[];
  rows: ProjectionRow[];
  totals: {
    totalIncome: number;
    totalExpense: number;
    totalNet: number;
    totalActualIncome: number;
    totalActualExpense: number;
    totalVariance: number;
    /** Drift al bucket actual (hoy). Null si todos los buckets son futuros. */
    currentDriftClp: number | null;
  };
  openingBalanceClp: number;
  openingBreakdown: OpeningBalanceBreakdown;
  /** Legacy: mismo orden que cumulativePoints.map(p => ({bucketKey, balanceClp: p.projectedClp})). */
  cumulativeBalances: { bucketKey: string; balanceClp: number }[];
  /** Saldo proyectado + real + drift por bucket. */
  cumulativePoints: CumulativeBalancePoint[];
  /** Links bancarios conciliados sin categoría exacta (cayeron a Otros
   *  o se descartaron). La UI puede mostrar un banner de "N conciliaciones
   *  sin clasificar". */
  unresolvedBankLinks: UnresolvedBankLinkInfo[];
}
