"use client";

import { useState } from "react";
import {
  ChevronDown,
  ArrowDownLeft,
  ArrowUpRight,
  type LucideIcon,
} from "lucide-react";
import { Surface } from "@/components/opai-ds";
import { cn } from "@/lib/utils";
import type {
  ProjectionBucket,
  VirtualOccurrence,
} from "@/modules/finance/cashflow/types";
import { fmtCLP } from "./format";
import {
  buildDetailRows,
  detailRowAmount,
  detailRowCount,
  type OccMeta,
} from "./projection-helpers";
import { MovementRow } from "./MovementRow";
import { GroupRow } from "./GroupRow";
import { QuickAddInline } from "./QuickAddInline";

interface Props {
  bucket: ProjectionBucket;
  meta: Map<string, OccMeta>;
  canManage: boolean;
  /** Filtro de texto opcional sobre las occurrences (cliente/contrato/instalación). */
  searchTerm?: string;
  onMove?: (occurrence: VirtualOccurrence) => void;
  /** Mueve la occurrence al bucket vecino. Si está definido, MovementRow
   *  muestra flechas ← → en lugar del picker. */
  onMoveDir?: (occurrence: VirtualOccurrence, dir: "left" | "right") => void;
  onDelete?: (occurrence: VirtualOccurrence) => void;
  canMoveLeft?: boolean;
  canMoveRight?: boolean;
  onOpenDetail?: (occurrence: VirtualOccurrence, meta?: OccMeta) => void;
  /** Callback tras agregar/mutar (router.refresh()). */
  onMutate?: () => void;
  /** Si true, la sección "Entra" arranca expandida (desktop). Mobile la deja
   *  colapsada para priorizar el saldo. */
  incomeDefaultOpen?: boolean;
}

/** Detalle de la semana seleccionada: Entra (INCOME) / Sale (EXPENSE), cada
 *  sección colapsable con subtotal. */
export function WeekDetail({
  bucket,
  meta,
  canManage,
  searchTerm,
  onMove,
  onMoveDir,
  onDelete,
  canMoveLeft,
  canMoveRight,
  onOpenDetail,
  onMutate,
  incomeDefaultOpen = false,
}: Props) {
  const term = (searchTerm ?? "").trim().toLowerCase();
  const matches = (o: VirtualOccurrence) =>
    !term ||
    [o.name, o.nickname, o.installationName, o.categoryName].some((s) =>
      (s ?? "").toLowerCase().includes(term),
    );
  const visible = bucket.occurrences.filter(matches);
  const income = visible.filter((o) => o.kind === "INCOME");
  const expense = visible.filter((o) => o.kind === "EXPENSE");
  return (
    <div className="space-y-3">
      <Section
        title="Entra"
        kind="INCOME"
        tone="ok"
        icon={ArrowDownLeft}
        defaultOpen={incomeDefaultOpen}
        bucket={bucket}
        occurrences={income}
        meta={meta}
        canManage={canManage}
        onMove={onMove}
        onMoveDir={onMoveDir}
        onDelete={onDelete}
        canMoveLeft={canMoveLeft}
        canMoveRight={canMoveRight}
        onOpenDetail={onOpenDetail}
        onMutate={onMutate}
      />
      <Section
        title="Sale"
        kind="EXPENSE"
        tone="danger"
        icon={ArrowUpRight}
        bucket={bucket}
        occurrences={expense}
        meta={meta}
        canManage={canManage}
        onMove={onMove}
        onMoveDir={onMoveDir}
        onDelete={onDelete}
        canMoveLeft={canMoveLeft}
        canMoveRight={canMoveRight}
        onOpenDetail={onOpenDetail}
        onMutate={onMutate}
      />
    </div>
  );
}

interface SectionProps {
  title: string;
  kind: "INCOME" | "EXPENSE";
  tone: "ok" | "danger";
  icon: LucideIcon;
  defaultOpen?: boolean;
  bucket: ProjectionBucket;
  occurrences: VirtualOccurrence[];
  meta: Map<string, OccMeta>;
  canManage: boolean;
  onMove?: (occurrence: VirtualOccurrence) => void;
  onMoveDir?: (occurrence: VirtualOccurrence, dir: "left" | "right") => void;
  onDelete?: (occurrence: VirtualOccurrence) => void;
  canMoveLeft?: boolean;
  canMoveRight?: boolean;
  onOpenDetail?: (occurrence: VirtualOccurrence, meta?: OccMeta) => void;
  onMutate?: () => void;
}

function Section({
  title,
  kind,
  tone,
  icon: Icon,
  defaultOpen = false,
  bucket,
  occurrences,
  meta,
  canManage,
  onMove,
  onMoveDir,
  onDelete,
  canMoveLeft,
  canMoveRight,
  onOpenDetail,
  onMutate,
}: SectionProps) {
  // Mobile-first: secciones Entra/Sale arrancan contraídas para que el saldo
  // de la semana sea lo primero que se vea. Carlos las expande on-demand.
  const [open, setOpen] = useState(defaultOpen);
  const [showZero, setShowZero] = useState(false);
  const { rows, zeroCount } = buildDetailRows(occurrences);
  const subtotal = rows.reduce((s, r) => s + detailRowAmount(r), 0);
  const count = rows.reduce((s, r) => s + detailRowCount(r), 0);
  // Sólo los $0 reales: las sombras auto-generadas (de-dup) se ocultan también
  // del listado "sin monto", coherente con que no cuentan en zeroCount.
  const zeroOccs = occurrences.filter(
    (o) => o.amountClp === 0 && !o.isAutoGenerated,
  );
  const toneFg = tone === "ok" ? "text-status-ok-fg" : "text-status-danger-fg";
  return (
    <Surface padding="sm">
      <div className="flex min-h-[44px] w-full items-center justify-between gap-2">
        <button
          type="button"
          onClick={() => setOpen((o) => !o)}
          aria-expanded={open}
          className="flex flex-1 items-center gap-2 text-left"
        >
          <ChevronDown
            className={cn(
              "h-4 w-4 text-ds-text-3 transition-transform",
              !open && "-rotate-90",
            )}
          />
          <Icon className={cn("h-4 w-4", toneFg)} />
          <span className="text-[13px] font-semibold text-ds-text-1">{title}</span>
          <span className="font-mono text-[12px] text-ds-text-3">{count}</span>
        </button>
        <span className="flex items-center gap-2">
          <span className={cn("font-mono text-[13px] tabular-nums", toneFg)}>
            {fmtCLP.format(subtotal)}
          </span>
          {canManage && (
            <QuickAddInline
              kind={kind}
              bucketStart={bucket.start}
              onAdded={onMutate}
            />
          )}
        </span>
      </div>
      {open &&
        (rows.length > 0 || zeroCount > 0 ? (
          <div className="mt-1 border-t border-ds-border-subtle">
            <div className="divide-y divide-ds-border-subtle">
              {rows.map((r, i) =>
                r.type === "separator" ? (
                  <div
                    key={`sep-${i}`}
                    className="flex items-center gap-2 px-1 py-1.5"
                  >
                    <div className="h-px flex-1 bg-ds-border-strong" />
                    <span className="text-[9px] font-semibold uppercase tracking-wider text-ds-text-3">
                      {r.label}
                    </span>
                    <div className="h-px flex-1 bg-ds-border-strong" />
                  </div>
                ) : r.type === "group" ? (
                  <GroupRow
                    key={`grp-${r.label}`}
                    label={r.label}
                    totalClp={r.totalClp}
                    items={r.items}
                    meta={meta}
                    canManage={canManage}
                    onMove={onMove}
                    onMoveDir={onMoveDir}
                    onDelete={onDelete}
                    canMoveLeft={canMoveLeft}
                    canMoveRight={canMoveRight}
                    onOpenDetail={onOpenDetail}
                    storageKey={`${bucket.key}:${r.label}`}
                  />
                ) : (
                  <MovementRow
                    key={r.occ.id ?? `s-${i}`}
                    occurrence={r.occ}
                    meta={r.occ.id ? meta.get(r.occ.id) : undefined}
                    canManage={canManage}
                    onMove={onMove}
                    onMoveDir={onMoveDir}
                    onDelete={onDelete}
                    canMoveLeft={canMoveLeft}
                    canMoveRight={canMoveRight}
                    onOpenDetail={onOpenDetail}
                  />
                ),
              )}
            </div>
            {zeroCount > 0 && (
              <div className="pt-1.5">
                <button
                  type="button"
                  onClick={() => setShowZero((v) => !v)}
                  aria-expanded={showZero}
                  className="flex min-h-[36px] items-center text-[12px] text-ds-text-3 hover:text-ds-text-2"
                >
                  {showZero ? "Ocultar sin monto" : `+${zeroCount} sin monto esta semana`}
                </button>
                {showZero && (
                  <div className="divide-y divide-ds-border-subtle border-t border-ds-border-subtle">
                    {zeroOccs.map((o, i) => (
                      <MovementRow
                        key={o.id ?? `z-${i}`}
                        occurrence={o}
                        meta={o.id ? meta.get(o.id) : undefined}
                        canManage={canManage}
                        onMove={onMove}
                        onMoveDir={onMoveDir}
                        onDelete={onDelete}
                        canMoveLeft={canMoveLeft}
                        canMoveRight={canMoveRight}
                        onOpenDetail={onOpenDetail}
                      />
                    ))}
                  </div>
                )}
              </div>
            )}
          </div>
        ) : (
          <p className="mt-2 text-[12px] text-ds-text-3">Sin movimientos.</p>
        ))}
    </Surface>
  );
}
